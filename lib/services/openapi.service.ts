import type { ProjectWithHierarchy } from "@/lib/services/project.service";
import type {
  OpenApiDocument,
  OpenApiPathItemObject,
  OpenApiOperationObject,
  OpenApiSchemaObject,
} from "@/lib/services/import.service";
import { getEffectiveRoutePath } from "@/lib/services/route-param.service";

/**
 * Strips internal engine annotations (such as x-fack-source, x-faker)
 * from the emitted OpenAPI response schemas.
 */
function sanitizeOpenApiSchema(node: unknown): unknown {
  if (!node || typeof node !== "object") {
    return node;
  }

  if (Array.isArray(node)) {
    return node.map((item) => sanitizeOpenApiSchema(item));
  }

  const record = node as Record<string, unknown>;
  const clean: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(record)) {
    if (key === "x-fack-source" || key === "x-faker" || key === "faker") {
      continue;
    }
    clean[key] = sanitizeOpenApiSchema(value);
  }

  return clean;
}

/**
 * Generates an OpenAPI 3.0.3 compliant JSON document for a given project.
 */
export function generateOpenApi(
  project: ProjectWithHierarchy,
): OpenApiDocument {
  const paths: Record<string, OpenApiPathItemObject> = {};

  const openApi: OpenApiDocument = {
    openapi: "3.0.3",
    info: {
      title: project.name,
      description: project.description || "Generated by Fack AI API Architect",
      version: "1.0.0",
    },
    paths,
  };

  for (const endpoint of project.endpoints) {
    for (const route of endpoint.routes) {
      const fullPath = getEffectiveRoutePath(endpoint.basePath, route.path);

      // Identify OpenAPI path parameters (e.g. /users/:id -> /users/{id})
      const openApiPath = fullPath.replace(/:([a-zA-Z0-9_]+)/g, "{$1}");
      const method = route.method.toLowerCase();

      // Parse responseSchema if possible
      let responseSchemaObj: OpenApiSchemaObject = {
        type: "object",
      };

      if (route.responseSchema) {
        try {
          const parsed: unknown = JSON.parse(route.responseSchema);
          if (parsed && typeof parsed === "object") {
            responseSchemaObj = sanitizeOpenApiSchema(
              parsed,
            ) as OpenApiSchemaObject;
          }
        } catch {
          // fallback to empty object if unparseable
        }
      }

      let pathItem = paths[openApiPath];
      if (!pathItem) {
        pathItem = {};
        paths[openApiPath] = pathItem;
      }

      // Extract path parameters array for OpenAPI
      const pathParams = Array.from(
        openApiPath.matchAll(/\{([a-zA-Z0-9_]+)\}/g),
      ).map((match) => ({
        name: match[1],
        in: "path",
        required: true,
        schema: {
          type: "string",
        },
      }));

      const operation: OpenApiOperationObject = {
        summary: `${route.method} ${openApiPath}`,
        tags: [endpoint.name],
        ...(pathParams.length > 0 ? { parameters: pathParams } : {}),
        responses: {
          [route.statusCode.toString()]: {
            description: `Response for ${route.statusCode}`,
            content: {
              "application/json": {
                schema: responseSchemaObj,
              },
            },
          },
        },
      };

      if (
        method === "get" ||
        method === "post" ||
        method === "put" ||
        method === "patch" ||
        method === "delete"
      ) {
        pathItem[method] = operation;
      }
    }
  }

  return openApi;
}
